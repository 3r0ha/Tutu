/**
 * Тесты отбора кандидатов.
 *
 * Чередование списков — не косметика: простое объединение стоило маршрута
 * Плёс → Казань, где въездные кандидаты заняли всю голову очереди и вытеснили
 * Иваново, единственный реальный выезд.
 */

import { strict as assert } from 'node:assert';
import { describe, it } from 'node:test';

import { interleave, addDays } from './planner.ts';

describe('чередование списков кандидатов', () => {
  it('берёт поочерёдно с обоих концов', () => {
    assert.deepEqual(
      interleave(['въезд1', 'въезд2'], ['выезд1', 'выезд2']),
      ['въезд1', 'выезд1', 'въезд2', 'выезд2'],
    );
  });

  it('оба конца попадают в голову очереди', () => {
    const merged = interleave(['A1', 'A2', 'A3', 'A4', 'A5', 'A6'], ['B1', 'B2']);
    assert.ok(merged.indexOf('B1') < 4, 'выездной кандидат вытеснен за отсечку');
  });

  it('повторы схлопываются, порядок первого вхождения сохраняется', () => {
    assert.deepEqual(interleave(['Москва', 'Тверь'], ['Москва', 'Клин']), [
      'Москва',
      'Тверь',
      'Клин',
    ]);
  });

  it('пустой список не мешает второму', () => {
    assert.deepEqual(interleave([], ['Мурманск']), ['Мурманск']);
    assert.deepEqual(interleave(['Иваново'], []), ['Иваново']);
  });
});

describe('сдвиг даты', () => {
  it('прибавляет сутки', () => {
    assert.equal(addDays('2026-09-11', 1), '2026-09-12');
  });

  it('переходит через границу месяца', () => {
    assert.equal(addDays('2026-09-30', 1), '2026-10-01');
  });

  it('переходит через границу года', () => {
    assert.equal(addDays('2026-12-31', 1), '2027-01-01');
  });

  it('учитывает високосный февраль', () => {
    assert.equal(addDays('2028-02-28', 1), '2028-02-29');
  });
});
