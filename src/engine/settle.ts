/**
 * Ожидание пачки запросов с мягким сроком.
 *
 * Замеры показали, что время ответа определяется не числом вызовов, а хвостом
 * апстрима: фаза не закрывается, пока не ответит самый медленный запрос, и один
 * такой превращал пятнадцать секунд в пятьдесят. Наращивание параллелизма
 * хвост только усиливает — вероятность поймать медленный ответ растёт вместе
 * с числом одновременных соединений.
 *
 * Поэтому мы перестаём ждать отстающих: как только набралось достаточно
 * результатов и вышел срок, фаза идёт дальше. Это продолжение общего правила
 * продукта — недостающее плечо деградирует до «такого варианта нет», а не
 * заставляет пользователя смотреть на спиннер.
 *
 * Отставшие запросы не отменяются: они честно доигрывают и оседают в кэше
 * клиента, поэтому следующий расчёт того же маршрута получит их бесплатно.
 *
 * Важная оговорка: срок применим только к спекулятивной части работы. Если
 * бросить по нему запрос, от которого зависит сам факт наличия маршрута,
 * продукт начнёт выдавать «доехать нельзя» вместо «мы не дождались». Такое
 * уже случалось: далёкие бесполезные города отвечали пустотой быстрее, чем
 * Мурманск — единственный настоящий шлюз к Териберке, и он отбрасывался
 * как отстающий. Поэтому вызывающий код обязан развести обязательную часть
 * и хвост сам (см. `core`/`tail` в планировщике).
 */

export interface SoftDeadline {
  /** Через сколько миллисекунд можно уходить, не дождавшись всех. */
  deadlineMs: number;
  /** Сколько ответов обязательно дождаться, даже если срок вышел. */
  minResults: number;
}

/**
 * Возвращает результаты в порядке задач. На месте не успевших — `null`,
 * неотличимый от честного отказа, который вызывающий код уже умеет обрабатывать.
 */
export function settleSoft<T>(
  tasks: Array<Promise<T | null>>,
  options: SoftDeadline,
): Promise<Array<T | null>> {
  if (tasks.length === 0) return Promise.resolve([]);

  return new Promise((resolve) => {
    const results: Array<T | null> = new Array(tasks.length).fill(null);
    const required = Math.min(options.minResults, tasks.length);

    let settled = 0;
    let expired = false;
    let finished = false;

    const finish = (): void => {
      if (finished) return;
      finished = true;
      clearTimeout(timer);
      resolve(results);
    };

    const timer = setTimeout(() => {
      expired = true;
      if (settled >= required) finish();
    }, options.deadlineMs);

    for (const [index, task] of tasks.entries()) {
      task
        .then((value) => {
          results[index] = value;
        })
        .catch(() => {
          // Отказ уже выражен значением `null` на своём месте.
        })
        .finally(() => {
          settled += 1;
          if (settled === tasks.length) finish();
          else if (expired && settled >= required) finish();
        });
    }
  });
}
