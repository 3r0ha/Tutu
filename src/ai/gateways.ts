/**
 * Подбор городов-шлюзов языковой моделью.
 *
 * Зачем это нужно. Статический каталог отбирает кандидатов по расстоянию, а
 * расстояние ничего не знает о транспортной реальности: до Суздаля едут через
 * Владимир и Иваново, до Плёса — через Кострому, до Териберки — через Мурманск,
 * и никакая гаверсинусова формула этого не подскажет. Хуже того, малого города
 * в каталоге обычно нет вовсе, и тогда отбор вырождается в произвольный.
 *
 * Модель закрывает ровно этот пробел — она предлагает гипотезы. Существование
 * рейса ни одна гипотеза не доказывает: каждый предложенный шлюз проверяется
 * живым запросом к Туту, и непроверенное до пользователя не доходит.
 *
 * Спрашивать нужно про оба конца. Долгое время спрашивалось только про въезд
 * в пункт назначения, и продукт умел добираться до малых городов, но не умел
 * из них уезжать: Териберка → Москва давала «выехать некуда», потому что
 * Мурманск — единственный выход — просто не попадал в кандидаты. Для обратной
 * дороги, которая у события есть всегда, это была дыра размером в половину
 * поездки.
 */

import { completeCached, extractJson, getProvider } from './provider.ts';

interface GatewayProposal {
  gateways?: string[];
}

const MAX_PROPOSED = 6;

function buildExitPrompt(origin: string): string {
  return [
    `Ты знаешь транспортную географию России.`,
    ``,
    `Задача: перечисли города, до которых из населённого пункта «${origin}» реально`,
    `существует прямое наземное или воздушное сообщение — то есть города, через`,
    `которые путешественник обычно выезжает из «${origin}».`,
    ``,
    `Правила:`,
    `- От 3 до ${MAX_PROPOSED} городов, самые вероятные первыми.`,
    `- Только реальные российские города, точные названия в именительном падеже.`,
    `- Включай ближайшие областные и районные центры, куда ходят автобусы или электрички.`,
    `- Включай крупный хаб, если туда есть прямой рейс.`,
    `- Не включай сам «${origin}».`,
    `- Если населённый пункт тебе неизвестен, верни пустой список.`,
    ``,
    `Ответь строго JSON без пояснений: {"gateways": ["Город", "Город"]}`,
  ].join('\n');
}

function buildPrompt(destination: string): string {
  return [
    `Ты знаешь транспортную географию России.`,
    ``,
    `Задача: перечисли города, из которых реально существует прямое наземное или воздушное`,
    `сообщение до населённого пункта «${destination}» — то есть города, через которые`,
    `путешественник обычно въезжает в «${destination}».`,
    ``,
    `Правила:`,
    `- От 3 до ${MAX_PROPOSED} городов, самые вероятные первыми.`,
    `- Только реальные российские города, точные названия в именительном падеже.`,
    `- Включай ближайшие областные и районные центры, откуда ходят автобусы или электрички.`,
    `- Включай крупный хаб (например, Москву), если оттуда есть прямой рейс.`,
    `- Не включай сам «${destination}».`,
    `- Если населённый пункт тебе неизвестен, верни пустой список.`,
    ``,
    `Ответь строго JSON без пояснений: {"gateways": ["Город", "Город"]}`,
  ].join('\n');
}

/**
 * Возвращает гипотезы о шлюзах. Пустой массив — штатный результат: он означает,
 * что подбор целиком остаётся за статическим каталогом.
 */
export async function proposeGateways(destination: string): Promise<string[]> {
  return ask(destination, 'entry');
}

/**
 * Города, через которые из населённого пункта обычно выезжают.
 *
 * Для крупного города ответ совпадёт со списком въезда, а для малого — нет:
 * из Териберки выезжают через Мурманск, и без этого вопроса он не появлялся
 * среди кандидатов вовсе.
 */
export async function proposeExits(origin: string): Promise<string[]> {
  return ask(origin, 'exit');
}

async function ask(city: string, direction: 'entry' | 'exit'): Promise<string[]> {
  if (getProvider().name === 'none') return [];

  const raw = await completeCached(
    `gateways:v2:${direction}:${city}`,
    direction === 'entry' ? buildPrompt(city) : buildExitPrompt(city),
  );
  const parsed = extractJson<GatewayProposal>(raw);
  if (!parsed?.gateways || !Array.isArray(parsed.gateways)) return [];

  const normalizedDestination = city.trim().toLowerCase();
  const seen = new Set<string>();
  const clean: string[] = [];

  for (const entry of parsed.gateways) {
    if (typeof entry !== 'string') continue;
    const name = entry.trim();
    // Отсекаем мусор вида пустых строк, фраз и повторов.
    if (name.length < 2 || name.length > 40) continue;
    const key = name.toLowerCase();
    if (key === normalizedDestination || seen.has(key)) continue;
    seen.add(key);
    clean.push(name);
    if (clean.length >= MAX_PROPOSED) break;
  }

  return clean;
}
